"""Renders the published results from run records alone (slice G).

`results.yaml` names what's published; everything else (every number,
every verdict) is recomputed from the committed records, with `compare`
re-deciding each comparison. The output is deterministic, so CI can check
that RESULTS.md and the README's headline table still match the records.
Nothing published is typed by hand."""

import json
import statistics
from pathlib import Path
from typing import Any, cast

import yaml

from agent_eval.compare import compare_runs
from agent_eval.records import load_run
from agent_eval.report import headline

README_START = "<!-- results:start (generated by `agent-eval publish`; do not edit) -->"
README_END = "<!-- results:end -->"


def _pct(n: int, d: int) -> str:
    return f"{100 * n / d:.1f}%" if d else "n/a"


def _pts(x: float) -> str:
    """A change in pass rate, in percentage points (not a relative %)."""
    return f"{100 * x:+.1f} pts"


def _run_row(repo: Path, entry: dict[str, Any]) -> dict[str, Any]:
    run = load_run(repo / "runs" / entry["run"])
    meta, h = run.meta, headline(run)
    secs = [t["seconds"] for t in run.trials if t["seconds"] is not None]
    cost_block: dict[str, Any] = meta["totals"].get("cost_usd") or {}
    cost: float | None = cost_block.get("usd")
    return {
        "label": entry["label"], "run": entry["run"], "suite": meta["suite"]["name"],
        "frozen": meta["suite"].get("frozen", False),
        "model": meta["agent"]["model"].rsplit("/", 1)[-1],
        "strict": f"{h['strict']}/{h['graded']} ({_pct(h['strict'], h['graded'])})",
        "lenient": f"{h['lenient']}/{h['graded']}",
        "pass_k": f"{h['pass_all_k']}/{h['tasks_counted']}",
        "errors": h["errors"],
        "cost": f"${cost:.3f}" if cost is not None else "unknown",
        "latency": f"{statistics.median(secs):.1f} s" if secs else "n/a",
        "date": str(meta.get("created_at", ""))[:10],
        "harness": meta["provenance"].get("harness_git"),
        "fingerprint": (meta["provenance"].get("data_fingerprint") or "")[:8],
        "server": meta["provenance"].get("server_version") or "not reported",
    }


def _comparison_row(repo: Path, entry: dict[str, Any]) -> dict[str, Any]:
    result = compare_runs(repo / "runs" / entry["baseline"], repo / "runs" / entry["candidate"])
    flagged = result.exit_code == 1
    interval = (f"{_pts(result.interval[0])} to {_pts(result.interval[1])}"
                if result.interval else "n/a")
    return {
        "label": entry["label"], "expected": entry["expected"],
        "verdict": result.verdict, "exit": result.exit_code,
        "change": _pts(result.point) if result.point is not None else "n/a",
        "interval": interval, "broken": len(result.broken),
        "warnings": "; ".join(result.warnings) or "–",
        # Only pre-registered proofs have an expectation; other comparisons
        # are published for information ("–").
        "as_expected": entry["expected"] not in ("flagged", "not flagged")
        or flagged == (entry["expected"] == "flagged"),
    }


def render(repo: Path) -> tuple[str, str]:
    """(RESULTS.md, the README's headline block)."""
    manifest = cast(dict[str, Any], yaml.safe_load((repo / "results.yaml").read_text(encoding="utf-8")))
    runs = [_run_row(repo, e) for e in manifest["runs"]]
    comps = [_comparison_row(repo, e) for e in manifest["comparisons"]]
    confs = [json.loads((repo / c).read_text(encoding="utf-8")) for c in manifest.get("confirmations", [])]

    out: list[str] = ["# Results", "",
                      "Generated by `agent-eval publish` from the committed run records; "
                      "CI fails if this file drifts from them. Methodology and caveats: "
                      "[README](README.md#methodology).", "", "## Runs", "",
                      "| Run | Suite | Model | Strict | Lenient | pass^5 | Errors | Cost | Median latency | Date |",
                      "|---|---|---|---|---|---|---|---|---|---|"]
    for r in runs:
        out.append(f"| {r['label']} (`{r['run']}`) | {r['suite']}{'' if r['frozen'] else ' (subset)'} | "
                   f"{r['model']} | {r['strict']} | {r['lenient']} | {r['pass_k']} | {r['errors']} | "
                   f"{r['cost']} | {r['latency']} | {r['date']} |")
    out += ["", "## Comparisons (the regression gate)", "",
            "| Comparison | Expected | Verdict (exit) | Change in strict pass rate | 95% interval | Broken tasks | Warnings |",
            "|---|---|---|---|---|---|---|"]
    for c in comps:
        mark = "" if c["as_expected"] else " **(not as expected)**"
        out.append(f"| {c['label']} | {c['expected']} | {c['verdict']} ({c['exit']}){mark} | "
                   f"{c['change']} | {c['interval']} | {c['broken']} | {c['warnings']} |")
    if confs:
        out += ["", "## Confirmations (fresh trials on the tasks that dropped)", "",
                "| Candidate vs baseline | Tasks × attempts | Original | Confirmed verdict | Change on those tasks | 95% interval |",
                "|---|---|---|---|---|---|"]
        for c in confs:
            out.append(f"| {c['candidate']} vs {c['baseline']} | {len(c['tasks'])} × {c['epochs']} | "
                       f"{_pts(c['original']['point'])} (inconclusive) | {c['verdict']} ({c['exit_code']}) | "
                       f"{_pts(c['point'])} | {_pts(c['interval'][0])} to {_pts(c['interval'][1])} |")
    out += ["", "## Provenance", "",
            "| Run | Harness commit | Data fingerprint | Server build | Frozen suite |",
            "|---|---|---|---|---|"]
    for r in runs:
        out.append(f"| `{r['run']}` | `{r['harness']}` | `{r['fingerprint']}` | {r['server']} | "
                   f"{'yes' if r['frozen'] else 'no'} |")
    results_md = "\n".join(out) + "\n"

    block = [README_START, "",
             "| Run | Strict pass rate | pass^5 | Cost | Median latency |", "|---|---|---|---|---|"]
    for r in runs:
        if r["run"] in manifest.get("headline", []):
            block.append(f"| {r['label']} | {r['strict']} | {r['pass_k']} | {r['cost']} | {r['latency']} |")
    block += ["", "| Regression check | Expected | Gate said |", "|---|---|---|"]
    for c in comps:
        block.append(f"| {c['label']} | {c['expected']} | {c['verdict']}, {c['change']} "
                     f"({c['interval']}){'' if c['as_expected'] else ' (not as expected)'} |")
    for c in confs:
        block.append(f"| Confirmation: {c['candidate']} vs {c['baseline']}, fresh trials | flagged if real | "
                     f"{c['verdict']}, {_pts(c['point'])} on {len(c['tasks'])} tasks |")
    block += ["", README_END]
    return results_md, "\n".join(block)


def apply_readme(readme: str, block: str) -> str:
    start, end = readme.index(README_START), readme.index(README_END) + len(README_END)
    return readme[:start] + block + readme[end:]
